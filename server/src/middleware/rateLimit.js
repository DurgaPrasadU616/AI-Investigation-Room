import rateLimit from 'express-rate-limit';

export const createCaseLimiter = rateLimit({
  windowMs: 60 * 60 * 1000,
  limit: 10,
  standardHeaders: 'draft-7',
  legacyHeaders: false,
  handler: (_req, res) => res.status(429).json({ success: false, error: { code: 'RATE_LIMITED', message: 'Too many mysteries were started from this address. Try again in an hour.' } }),
});
